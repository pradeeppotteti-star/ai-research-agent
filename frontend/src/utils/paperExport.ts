/**
 * Downloads a spreadsheet (.csv) containing all 25 papers with columns:
 * Citation #, Title, Authors, Year, Source, Venue, DOI, Primary URL, Abstract
 */
export function downloadAllPapersCSV(papers: Paper[], query: string): void {
  const cleanTitle = query.replace(/[^a-zA-Z0-9\s]/g, ' ').trim().slice(0, 40).replace(/\s+/g, '_');
  const filename = `All_${papers.length}_Research_Papers_${cleanTitle}.csv`;

  const headers = ['Citation #', 'Paper Title', 'Authors', 'Year', 'Source', 'Venue', 'DOI', 'Primary URL', 'PDF URL', 'Abstract'];

  const rows = papers.map((p, idx) => {
    const authors = p.authors ? p.authors.join('; ') : 'Authors';
    const venue = p.venue || 'Academic Repository';
    const doi = p.doi || '';
    const primaryUrl = p.urls?.primary || '';
    const pdfUrl = p.urls?.pdf || '';
    const cleanAbstract = (p.abstract || '').replace(/[\r\n]+/g, ' ').replace(/"/g, '""');
    const cleanTitleCell = (p.title || '').replace(/"/g, '""');

    return [
      idx + 1,
      `"${cleanTitleCell}"`,
      `"${authors}"`,
      p.publicationDate || '2024',
      `"${p.source}"`,
      `"${venue}"`,
      `"${doi}"`,
      `"${primaryUrl}"`,
      `"${pdfUrl}"`,
      `"${cleanAbstract}"`,
    ].join(',');
  });

  const csvContent = '\ufeff' + [headers.join(','), ...rows].join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8' });
  const element = document.createElement('a');
  element.href = URL.createObjectURL(blob);
  element.download = filename;
  document.body.appendChild(element);
  element.click();
  document.body.removeChild(element);
}

/**
 * Downloads full JSON dataset containing all papers and extracted sections.
 */
export function downloadAllPapersJSON(papers: Paper[], query: string): void {
  const cleanTitle = query.replace(/[^a-zA-Z0-9\s]/g, ' ').trim().slice(0, 40).replace(/\s+/g, '_');
  const filename = `All_${papers.length}_Research_Papers_${cleanTitle}.json`;

  const payload = {
    query,
    totalPapers: papers.length,
    exportedAt: new Date().toISOString(),
    papers,
  };

  const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json;charset=utf-8' });
  const element = document.createElement('a');
  element.href = URL.createObjectURL(blob);
  element.download = filename;
  document.body.appendChild(element);
  element.click();
  document.body.removeChild(element);
}
